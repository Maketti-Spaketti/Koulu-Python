def add(value1: float, value2: float) -> float:
    """Returns the sum of two values.
    Args:
        value1 (float): The first value.
        value2 (float): The second value.

    Returns:
        float: The sum.
    """
    return value1 + value2


def substract(value1: float, value2: float) -> float:
    """Returns the difference of two values.
    Args:
        value1 (float): The first value.
        value2 (float): The second value.

    Returns:
        float: The difference.
    """
    return value1 - value2


def multiply(value1: float, value2: float) -> float:
    """Returns the product of two values.
    Args:
        value1 (float): The first value.
        value2 (float): The second value.

    Returns:
        float: The product.
    """
    return value1 * value2


def divide(value1: float, value2: float) -> float:
    """Returns the quotient of two values.
    Args:
        value1 (float): The first value.
        value2 (float): The second value.

    Returns:
        float: The quotient.
    """
    return value1 / value2
